#!/bin/sh
# ============================================================================
# 容器入口：补数据 → 验沙箱 → 交棒给 app.py
#
# 只做三件事，每件都必须在这里做（而不是塞进 app.py）：
#   1. 把镜像里的 seed/ 补进 data/ 卷——只补缺失，从不覆盖；
#      命名卷其实会被 Docker 自动填好，这一步是给 bind mount / emptyDir 兜底；
#   2. 沙箱能不能用应该**在启动日志里就说清楚**，而不是等第一题判错才暴露；
#   3. exec 交棒，让 app.py 成为 PID 1 之后的那个进程，收到 SIGTERM。
#
# 刻意不写 `set -e` 之外的花活：这个脚本跑在只读根文件系统上，
# 任何一步失败都不该阻断启动——课程页面在编译器坏掉时依然该能看。
# ============================================================================
set -eu

DATA_DIR="${CMASTER_DATA:-/app/data}"
SEED_DIR="/app/seed"

# ---------------------------------------------------------------------------
# 1. 补数据文件（只补缺失，从不覆盖）
#
# 事实先说准：命名卷第一次挂载时，Docker 会把镜像里该路径的内容复制进
# 空卷，所以按 compose 现在的写法 data/ 本来就不空。这段是**兜底**，
# 兜的是「运维把挂载换成 bind mount 或 emptyDir」——那两种一个字节都不复制，
# 宿主机的空目录会原样盖住镜像内容，结果是页面能开、一道题都没有。
#
# 为什么不干脆把 data/ 做成 bind mount 省掉这段：那样仓库里的 data/ 一旦
# 被宿主机改写，镜像就「不是那个镜像」了，可复现性没了。命名卷负责持久，
# seed 负责「换挂载方式也不崩」，两件事分开管。
#
# 注意 cp 用的是「目标不存在才复制」，不是 cp -n 一把梭：进度文件
# 每一题都在变，启动时覆盖等于每次重启都清空用户历史。
#
# 顺带一个已知的小空洞，写在这里而不是藏起来：`*` 不匹配隐藏文件，
# 所以 data/.secret 永远不会被补种。这是**想要的**——session 密钥应该是
# 每次部署各自生成（app.py 发现没有就自己造一个），而不是全网共用一个
# 从镜像里带出来的。如果哪天往 data/ 里加了别的隐藏文件，记得回来看这行。
# ---------------------------------------------------------------------------
if [ -d "$SEED_DIR" ]; then
    mkdir -p "$DATA_DIR" 2>/dev/null || true
    for src in "$SEED_DIR"/*; do
        [ -e "$src" ] || continue
        name=$(basename "$src")
        if [ -d "$src" ]; then
            [ -d "$DATA_DIR/$name" ] || cp -a "$src" "$DATA_DIR/$name" 2>/dev/null || true
        else
            [ -e "$DATA_DIR/$name" ] || cp -a "$src" "$DATA_DIR/$name" 2>/dev/null || true
        fi
    done
fi

# ---------------------------------------------------------------------------
# 2. 沙箱自检（轻量版：只做 resolve + probe，不跑五组实验）
#
# 完整的 selftest 要真编译五个程序跑一遍，Linux 上十几秒，放在启动路径上
# 会让每次重启都慢一拍。这里只回答一个问题：**runner 这个二进制在这台
# 机器上能不能执行**。答案是「能」就继续；「不能」就把原因打出来，
# 由 /readyz 报 503、/admin 显示降级——启动本身不阻断。
#
# 真正的五组验证在 /admin 上点「重跑自检」。这个分工是有意的：
# 启动要快且绝不失败，验收要全且必须有人看。
# ---------------------------------------------------------------------------
echo "[cmaster] 检查判题沙箱 …"
python - <<'PY' || echo "[cmaster] ⚠️ 沙箱检查脚本本身出错，判题可能降级，请查看 /admin"
import sys
try:
    import sandbox
except Exception as e:                      # noqa: BLE001
    print("[cmaster] ⚠️ 无法导入 sandbox 模块：%s" % e)
    sys.exit(0)

info = sandbox.available()
if info["ok"]:
    print("[cmaster] 沙箱就绪：%s（%s）" % (info["backend"], info["mode"]))
    if info.get("build_ms"):
        print("[cmaster]   宿主构建耗时 %d ms" % info["build_ms"])
else:
    # 这里说的是「现在这个进程能不能用沙箱跑用户代码」，不是「镜像坏了」。
    print("[cmaster] ⚠️ 沙箱不可用：%s" % (info.get("reason") or "未知原因"))
    print("[cmaster] ⚠️ 判题将按 sandbox.py 的策略处理；"
          "本该可用却初始化失败时会 fail-closed（拒绝执行）")
PY

# ---------------------------------------------------------------------------
# 3. 交棒
#
# exec 不能省：不 exec 的话 app.py 是 sh 的子进程，docker stop 的 SIGTERM
# 打给 sh，python 收不到，等 10 秒后被 SIGKILL——正在判的题直接没结果。
# "$@" 让 `docker run image bash` 这类临时进入的用法也能工作。
# ---------------------------------------------------------------------------
exec "$@"
